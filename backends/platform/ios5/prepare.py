#!/usr/bin/env python3
import argparse
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
import shutil
import sys


def parse_patch(text):
    files = {}
    path = None
    lines = text.splitlines(keepends=True)
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith('+++ b/'):
            path = line[6:].rstrip('\n')
            parts = PurePosixPath(path).parts
            if '..' in parts or path.startswith('/') or parts[0] not in ('backends', 'graphics', 'base'):
                raise ValueError('Disallowed override path: ' + path)
            files[path] = []
        elif line.startswith('@@ '):
            match = re.match(r'@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@', line)
            if not path or not match:
                raise ValueError('Malformed hunk: ' + line)
            old, new = [], []
            i += 1
            while i < len(lines) and lines[i][:1] in (' ', '+', '-') and not lines[i].startswith(('--- ', '+++ ')):
                item = lines[i]
                if item[0] in ' -': old.append(item[1:])
                if item[0] in ' +': new.append(item[1:])
                i += 1
            if len(old) != int(match[2] or 1) or len(new) != int(match[4] or 1) or not old:
                raise ValueError('Invalid/context-free hunk in ' + path)
            files[path].append((int(match[1]) - 1, old, new))
            continue
        i += 1
    if not files or any(not hunks for hunks in files.values()):
        raise ValueError('Empty or unsupported compatibility patch')
    return files


def apply_hunks(path, text, hunks):
    lines = text.splitlines(keepends=True)
    delta = 0
    previous_end = 0
    for number, (position, old, new) in enumerate(hunks, 1):
        expected = position + delta
        if expected >= previous_end and lines[expected:expected + len(old)] == old:
            at = expected
        else:
            matches = [i for i in range(previous_end, len(lines) - len(old) + 1)
                       if lines[i:i + len(old)] == old]
            if len(matches) != 1:
                raise ValueError(f'{path}: hunk {number} conflicts with updated source ({len(matches)} exact matches); review compat.patch')
            at = matches[0]
        lines[at:at + len(old)] = new
        delta = at - position + len(new) - len(old)
        previous_end = at + len(new)
    return ''.join(lines)


def replace_file(path, content):
    if path.is_symlink(): path.unlink()
    if path.is_file() and path.read_bytes() == content: return
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + '.ios5-tmp')
    temporary.write_bytes(content)
    temporary.replace(path)


def remove_generated(path):
    if path.is_symlink() or path.is_file(): path.unlink()
    elif path.exists(): shutil.rmtree(path)


def prepare(source, output, patch):
    source = source.resolve()
    output = output.absolute()
    if output.is_symlink() or output == source or source in output.parents:
        raise ValueError('Use an out-of-source iOS5 build directory outside the source tree')
    marker = output / '.ios5-generated'
    if output.exists() and not marker.is_file():
        raise ValueError('Refusing to replace a directory not generated by the iOS5 backend: ' + str(output))
    changes = parse_patch(patch.read_text())
    rendered, hashes = {}, {}
    for name, hunks in changes.items():
        original = (source / name).read_text()
        rendered[name] = apply_hunks(name, original, hunks).encode()
        hashes[name] = {'source': hashlib.sha256(original.encode()).hexdigest(),
                        'override': hashlib.sha256(rendered[name]).hexdigest()}
    directories = {''}
    for name in changes:
        directories.update(str(parent) for parent in PurePosixPath(name).parents if str(parent) != '.')
    output.mkdir(parents=True, exist_ok=True)
    marker.write_text('Generated iOS5 source view. Edit the original source or compat.patch.\n')

    def mirror(relative):
        src, dst = source / relative, output / relative
        wanted = {child.name for child in src.iterdir() if child.name != '.git'}
        for old in dst.iterdir():
            if old.name not in wanted and not (not relative and old.name.startswith('.ios5-')):
                remove_generated(old)
        for name in sorted(wanted):
            child = str(PurePosixPath(relative) / name)
            target = output / child
            if child in rendered:
                replace_file(target, rendered[child])
            elif child in directories:
                if target.is_symlink(): target.unlink()
                target.mkdir(exist_ok=True)
                mirror(child)
            else:
                original = source / child
                if target.is_symlink() and target.readlink() == original: continue
                remove_generated(target)
                target.symlink_to(original, target_is_directory=original.is_dir())
    mirror('')
    manifest = {'source': str(source), 'patch_sha256': hashlib.sha256(patch.read_bytes()).hexdigest(), 'files': hashes}
    replace_file(output / '.ios5-manifest.json', (json.dumps(manifest, indent=2) + '\n').encode())
    prerequisites = [source / name for name in sorted(changes)] + [source / name for name in sorted(directories)]
    if any(' ' in str(p) or '#' in str(p) or '$' in str(p) for p in prerequisites):
        raise ValueError('iOS5 make paths must not contain spaces, # or $')
    make = 'IOS5_ORIGINAL_SOURCE := ' + str(source) + '\n'
    make += 'IOS5_OVERRIDE_INPUTS := ' + ' '.join(map(str, prerequisites)) + '\n'
    replace_file(output / '.ios5-overrides.mk', make.encode())
    (output / '.ios5-overrides.mk').touch()
    print(f'iOS5: generated {len(changes)} checked overrides; original sources untouched')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--source', type=Path, default=Path(__file__).resolve().parents[3])
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    try:
        prepare(args.source, args.output, args.source / 'backends/platform/ios5/compat.patch')
    except (ValueError, OSError) as error:
        parser.exit(1, 'iOS5 override error: ' + str(error) + '\n')


if __name__ == '__main__':
    main()
